static inline uint16_t birthdayRgb565(uint8_t c) {
  uint8_t r = c & 0xE0; r |= (r >> 3);
  uint8_t g = (c & 0x1C) << 3; g |= (g >> 3);
  uint8_t b = (c & 0x03) << 6; b |= (b >> 2) | (b >> 4);
  return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3);
}
